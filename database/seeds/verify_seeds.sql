-- Resumen de verificación de catálogos canónicos.
SET PAGESIZE 100;
SET LINESIZE 180;

SELECT COUNT(*) ROLE_COUNT FROM ROLES
WHERE ROLE_ID IN (
    '99999999-9999-9999-9999-999999999999',
    '11111111-1111-1111-1111-111111111111',
    '44444444-4444-4444-4444-444444444444',
    '55555555-5555-5555-5555-555555555555',
    '66666666-6666-6666-6666-666666666666',
    '77777777-7777-7777-7777-777777777777');

SELECT
    (SELECT COUNT(*) FROM MODULES) MODULES,
    (SELECT COUNT(*) FROM ROLE_PERMISSIONS) ROLE_PERMISSIONS,
    (SELECT COUNT(*) FROM STATUS_APPOINTMENTS) APPOINTMENT_STATUSES,
    (SELECT COUNT(*) FROM CONVERSATIONS_STATUSES) CONVERSATION_STATUSES,
    (SELECT COUNT(*) FROM SENDER_TYPES) SENDER_TYPES,
    (SELECT COUNT(*) FROM MESSAGE_TYPES) MESSAGE_TYPES,
    (SELECT COUNT(*) FROM PRIORITY) PRIORITIES,
    (SELECT COUNT(*) FROM ESCALATIONS_STATUSES) ESCALATION_STATUSES,
    (SELECT COUNT(*) FROM AI_RUNS_STATUSES) AI_RUN_STATUSES,
    (SELECT COUNT(*) FROM TYPE_SERVICES) TYPE_SERVICES,
    (SELECT COUNT(*) FROM SPECIES) SPECIES,
    (SELECT COUNT(*) FROM SPECIALTIES) SPECIALTIES
FROM DUAL;

SELECT ROLE_ID, NAME FROM ROLES ORDER BY NAME;
SELECT STATUS_APPOINTMENT_ID, NAME FROM STATUS_APPOINTMENTS ORDER BY NAME;
SELECT CONVERSATIONS_STATUSES_ID, NAME_STATUS FROM CONVERSATIONS_STATUSES ORDER BY NAME_STATUS;
SELECT SENDER_TYPES_ID, NAME_TYPE FROM SENDER_TYPES ORDER BY NAME_TYPE;
