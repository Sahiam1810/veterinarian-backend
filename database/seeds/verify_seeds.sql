PROMPT 5. DETALLE DE CITAS MÉDICAS REGISTRADAS
PROMPT =========================================================================

SELECT 
    a.APPOINTMENT_ID,
    TO_CHAR(a.SCHEDULED_START, 'YYYY-MM-DD HH24:MI') AS FECHA_HORA,
    p.NAME AS MASCOTA,
    u_vet.FULL_NAME AS VETERINARIO,
    srv.NAME AS SERVICIO,
    sa.NAME AS ESTADO_CITA,
    a.REQUESTER_PHONE_NUMBER AS TELEFONO
FROM APPOINTMENTS a
JOIN CLIENTS_PETS cp ON a.CLIENT_PET_ID = cp.CLIENT_PET_ID
JOIN PETS p ON cp.PET_ID = p.PET_ID
JOIN VETERINARIANS v ON a.VETERINARIAN_ID = v.VETERINARIAN_ID
JOIN USERS u_vet ON v.USER_ID = u_vet.USER_ID
JOIN SERVICES srv ON a.SERVICE_ID = srv.SERVICE_ID
JOIN STATUS_APPOINTMENTS sa ON a.STATUS_ID = sa.STATUS_APPOINTMENT_ID
ORDER BY a.SCHEDULED_START DESC;

