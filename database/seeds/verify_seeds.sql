PROMPT 6. DETALLE DE HISTORIAS CLÍNICAS Y VACUNACIÓN
PROMPT =========================================================================

SELECT 
    mr.RECORD_ID,
    p.NAME AS MASCOTA,
    d.NAME AS DIAGNOSTICO,
    mr.WEIGHT_AT_VISIT AS PESO_KG,
    mr.TEMPERATURE AS TEMP_C,
    mr.TREATMENT AS TRATAMIENTO,
    NVL(v.VACCINE_NAME, 'Sin vacuna') AS VACUNA_APLICADA
FROM MEDICAL_RECORDS mr
JOIN CLIENTS_PETS cp ON mr.CLIENT_PET_ID = cp.CLIENT_PET_ID
JOIN PETS p ON cp.PET_ID = p.PET_ID
JOIN DIAGNOSTICS d ON mr.DIAGNOSTIC_ID = d.ID
LEFT JOIN VACCINATIONS v ON mr.RECORD_ID = v.RECORD_ID
ORDER BY p.NAME;

