PROMPT 3. DETALLE DE USUARIOS, CUENTAS Y ACCESO AL SISTEMA
PROMPT =========================================================================

SELECT 
    u.EMAIL,
    r.NAME AS ROL,
    u.FULL_NAME,
    NVL(ua.USERNAME, '[SIN CUENTA]') AS USERNAME,
    NVL(ua.STATUS, '[INACTIVO]') AS ESTADO_CUENTA,
    CASE WHEN uc.PASSWORD_HASH IS NOT NULL THEN 'SI' ELSE 'NO' END AS TIENE_PASSWORD
FROM USERS u
JOIN ROLES r ON u.ROLE_ID = r.ROLE_ID
LEFT JOIN USER_ACCOUNTS ua ON u.USER_ID = ua.USER_ID
LEFT JOIN USER_CREDENTIALS uc ON ua.ACCOUNT_ID = uc.ACCOUNT_ID
ORDER BY r.NAME, u.EMAIL;

