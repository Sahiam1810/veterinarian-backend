-- Cliente sin permisos de plataforma web (ADR Opción A).
-- Limpia residuales de ROLE_PERMISSIONS y USER_PERMISSIONS para el rol Cliente.
SET DEFINE OFF;

DELETE FROM ROLE_PERMISSIONS
WHERE ROLE_ID = '77777777-7777-7777-7777-777777777777';

DELETE FROM USER_PERMISSIONS
WHERE USER_ID IN (
    SELECT USER_ID FROM USERS WHERE ROLE_ID = '77777777-7777-7777-7777-777777777777'
);

COMMIT;
